"""
Arithmetic operator merupakan operasi layaknya di matematika, ada penjumlahan, pengurangan, perkalian, dan pembagian.
"""

# 1. penjumlahan 
print("-"*20)
print("Penjumlahan")
print("-"*20) 


angka_1 = 10 
angka_2 = 20

hasil = angka_1 + angka_2 

print(f"Hasil {angka_1} + {angka_2} = {hasil}")

# Versi singkat / cepatnya
angka_3 = 50 
# hasil = hasil + angka_3
hasil += angka_3
print(f"Hasil {angka_3} + {30} = {hasil}")

# 2. pengurangan 
print("-"*20)
print("Pengurangan")
print("-"*20) 


angka_4 = 40 
angka_5 = 20

hasil_pengurangan = angka_4 - angka_5 

print(f"Hasil {angka_4} - {angka_5} = {hasil_pengurangan}")

# Versi singkat / cepatnya
angka_6 = 10
# hasil_pengurangan = hasil_pengurangan - angka_3
hasil_pengurangan -= angka_6
print(f"Hasil {20} - {angka_6} = {hasil_pengurangan}")


# 3. Perkalian 
print("-"*20)
print("Perkalian")
print("-"*20) 


angka_10 = 40 
angka_8 = 20

hasil_perkalian = angka_10 * angka_8 

print(f"Hasil {angka_10} * {angka_8} = {hasil_perkalian}")

# Versi singkat / cepatnya
angka_9 = 10
# hasil_perkalian = hasil_perkalian * angka_3
hasil_perkalian *= angka_9
print(f"Hasil {800} * {angka_9} = {hasil_perkalian}")


# 4. Pembagian 
print("-"*20)
print("Pembagian")
print("-"*20) 


angka_10 = 40 
angka_11 = 20

hasil_pembagian = angka_10 / angka_11 

print(f"Hasil {angka_10} / {angka_11} = {hasil_pembagian}")

# Versi singkat / cepatnya
angka_12 = 2
# hasil_pembagian = hasil_pembagian * angka_3
hasil_pembagian /= angka_12
print(f"Hasil {2} / {angka_12} = {hasil_pembagian}")

# 5. Pembagian 
print("-"*20)
print("Pembagian -Integer")
print("-"*20) 


angka_10 = 70 
angka_11 = 20

hasil_pembagian = angka_10 // angka_11 

print(f"Hasil {angka_10} // {angka_11} = {hasil_pembagian}")

# Versi singkat / cepatnya
angka_12 = 2
# hasil_pembagian = hasil_pembagian * angka_3
hasil_pembagian //= angka_12
print(f"Hasil {2} // {angka_12} = {hasil_pembagian}")

# 6. Modulo
print("-"*20)
print("Modulo")
print("-"*20) 


angka_13 = 1 
angka_14 = 20

hasil_penjumlahan = angka_13 + angka_14 

print(f"Hasil {angka_13} + {angka_14} = {hasil_penjumlahan}")

# Versi singkat / cepatnya
angka_15 = 2
hasil_modulo = hasil_penjumlahan % angka_15
print(f"Hasil {21} % {angka_15} = {hasil_modulo}")




