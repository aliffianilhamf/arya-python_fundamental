number_1 = 10 
number_2 = 5 

# 1. Lebih dari 
hasil = number_1 > number_2 # True
print(hasil)

# 2. Kurang dari 
hasil = number_1 < number_2 # False 
print(hasil)

# 3. Lebih besar sama dengan 
number_3 = 10
# hasil = number_1 > number_3 # False
hasil = number_1 >= number_3 # True
print(hasil)

# 4. kurang dari sama dengan 
# hasil = number_1 < number_3 # False
hasil = number_1 <= number_3 # True
print(hasil)

# 5. sama dengan sama dengan (sama dengan)
hasil = number_1 == number_3 # True 
# hasil = number_1 == number_2 # False
print(hasil)

# 6. tidak sama dengan 
hasil = number_1 != number_3 # False 
# hasil = number_1 != number_2 # True
print(hasil)